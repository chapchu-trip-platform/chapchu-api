--
-- breed_id는 V7에서 INT GENERATED ALWAYS AS IDENTITY가 되었으므로 값을 지정하지 않는다.
-- breed_name에 UNIQUE를 걸어 앞으로 같은 이름이 두 번 들어가는 것을 막고,
-- ON CONFLICT로 이미 있는 이름은 건너뛴다.
-- (ALTER TABLE 자체는 재실행 불가다. Flyway가 마이그레이션을 한 번만 돌리므로 문제되지 않는다.)

ALTER TABLE breeds ADD CONSTRAINT uq_breeds_breed_name UNIQUE (breed_name);

